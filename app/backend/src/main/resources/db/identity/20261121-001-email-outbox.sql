CREATE TABLE EMAIL_OUTBOX (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ACCOUNT_ID BIGINT REFERENCES ACCOUNT(ID) ON DELETE SET NULL,
    INVITATION_ID BIGINT REFERENCES TEAM_INVITATION(ID) ON DELETE SET NULL,
    SERIES_ID BIGINT,
    RECIPIENT VARCHAR(254) NOT NULL,
    STATUS VARCHAR(20) NOT NULL,
    CREATED_AT TIMESTAMPTZ NOT NULL,
    PAYLOAD TEXT,
    TOKEN_HASH VARCHAR(64),
    ATTEMPTS INTEGER NOT NULL DEFAULT 0,
    FIRST_ATTEMPT_AT TIMESTAMPTZ,
    NEXT_SUBMISSION_AT TIMESTAMPTZ,
    SUBMISSION_IN_FLIGHT BOOLEAN NOT NULL DEFAULT FALSE,
    SUBMISSION_UNCERTAIN BOOLEAN NOT NULL DEFAULT FALSE,
    PROVIDER_ID UUID UNIQUE,
    ACCEPTED_AT TIMESTAMPTZ,
    NEXT_LOOKUP_AT TIMESTAMPTZ,
    OUTCOME_AT TIMESTAMPTZ,
    FAILURE_CODE VARCHAR(100),
    PREVIOUS_TOKEN_HASH VARCHAR(64),
    PREVIOUS_EXPIRES_AT TIMESTAMPTZ,
    PREVIOUS_SENT_AT TIMESTAMPTZ
);

CREATE UNIQUE INDEX EMAIL_OUTBOX_TOKEN ON EMAIL_OUTBOX (TOKEN_HASH) WHERE TOKEN_HASH IS NOT NULL;
CREATE INDEX EMAIL_OUTBOX_SUBMISSION ON EMAIL_OUTBOX (NEXT_SUBMISSION_AT)
    WHERE STATUS = 'PENDING';
CREATE INDEX EMAIL_OUTBOX_LOOKUP ON EMAIL_OUTBOX (NEXT_LOOKUP_AT)
    WHERE STATUS = 'PROVIDER_ACCEPTED';
CREATE INDEX EMAIL_OUTBOX_RECIPIENT ON EMAIL_OUTBOX (RECIPIENT, CREATED_AT DESC);
CREATE INDEX EMAIL_OUTBOX_ACCOUNT ON EMAIL_OUTBOX (ACCOUNT_ID, CREATED_AT);
CREATE INDEX EMAIL_OUTBOX_INVITATION ON EMAIL_OUTBOX (INVITATION_ID, CREATED_AT);
CREATE INDEX EMAIL_OUTBOX_SERIES ON EMAIL_OUTBOX (SERIES_ID, CREATED_AT);

CREATE TABLE EMAIL_DELIVERY_EVENT (
    EVENT_KEY VARCHAR(255) PRIMARY KEY,
    EMAIL_ID BIGINT NOT NULL REFERENCES EMAIL_OUTBOX(ID),
    KIND VARCHAR(100) NOT NULL,
    OCCURRED_AT TIMESTAMPTZ NOT NULL,
    RECORDED_AT TIMESTAMPTZ NOT NULL,
    REASON VARCHAR(1000)
);

CREATE INDEX EMAIL_DELIVERY_EVENT_HISTORY ON EMAIL_DELIVERY_EVENT (EMAIL_ID, RECORDED_AT);

ALTER TABLE VERIFICATION_EMAIL ADD COLUMN LATEST_EMAIL_ID BIGINT REFERENCES EMAIL_OUTBOX(ID);
ALTER TABLE TEAM_INVITATION ADD COLUMN LATEST_EMAIL_ID BIGINT REFERENCES EMAIL_OUTBOX(ID);

-- Keep usable links and transport history from the retired relay. Its uncertain
-- submissions cannot safely be replayed through a different provider.
INSERT INTO EMAIL_OUTBOX (ACCOUNT_ID, RECIPIENT, STATUS, CREATED_AT, ACCEPTED_AT, FAILURE_CODE)
SELECT ACCOUNT_ID, RECIPIENT, 'UNKNOWN',
       COALESCE(LAST_ATTEMPT_AT, LAST_SENT_AT, CURRENT_TIMESTAMP), LAST_SENT_AT,
       CASE WHEN STATUS = 'SMTP_ACCEPTED' THEN 'LEGACY_DELIVERY_UNKNOWN' ELSE 'LEGACY_SUBMISSION_UNKNOWN' END
FROM VERIFICATION_EMAIL
WHERE STATUS IN ('SMTP_ACCEPTED', 'SENDING')
    OR (STATUS = 'FAILED' AND (
        FAILURE_CODE IS NULL OR FAILURE_CODE NOT IN (
            'SMTP_AUTHENTICATION_FAILED', 'SMTP_FROM_NOT_CONFIGURED', 'SMTP_MESSAGE_INVALID'
        )
    ));

UPDATE VERIFICATION_EMAIL v SET LATEST_EMAIL_ID = e.ID
FROM EMAIL_OUTBOX e WHERE e.ACCOUNT_ID = v.ACCOUNT_ID;

INSERT INTO EMAIL_OUTBOX (INVITATION_ID, RECIPIENT, STATUS, CREATED_AT, ACCEPTED_AT, FAILURE_CODE)
SELECT ID, EMAIL,
       CASE WHEN STATUS = 'FAILED' AND REPLACEMENT_TOKEN_HASH IS NULL THEN 'FAILED' ELSE 'UNKNOWN' END,
       COALESCE(REPLACEMENT_ATTEMPTED_AT, ATTEMPTED_AT), SENT_AT,
       CASE
           WHEN STATUS = 'SENDING' OR REPLACEMENT_TOKEN_HASH IS NOT NULL THEN 'LEGACY_SUBMISSION_UNKNOWN'
           WHEN STATUS = 'FAILED' THEN COALESCE(FAILURE_CODE, 'LEGACY_SUBMISSION_FAILED')
           ELSE 'LEGACY_DELIVERY_UNKNOWN'
       END
FROM TEAM_INVITATION
WHERE STATUS IN ('SMTP_ACCEPTED', 'SENDING', 'FAILED', 'ACCEPTED');

UPDATE TEAM_INVITATION i SET LATEST_EMAIL_ID = e.ID
FROM EMAIL_OUTBOX e WHERE e.INVITATION_ID = i.ID;

INSERT INTO EMAIL_DELIVERY_EVENT (EVENT_KEY, EMAIL_ID, KIND, OCCURRED_AT, RECORDED_AT, REASON)
SELECT 'legacy:' || e.ID, e.ID, e.FAILURE_CODE, e.CREATED_AT, CURRENT_TIMESTAMP,
       NULLIF(CONCAT_WS(' / ', COALESCE(v.SMTP_MESSAGE_ID, i.SMTP_MESSAGE_ID),
                        COALESCE(v.FAILURE_CODE, i.FAILURE_CODE)), '')
FROM EMAIL_OUTBOX e
LEFT JOIN VERIFICATION_EMAIL v ON v.ACCOUNT_ID = e.ACCOUNT_ID
LEFT JOIN TEAM_INVITATION i ON i.ID = e.INVITATION_ID;

UPDATE TEAM_INVITATION SET STATUS = 'READY' WHERE STATUS = 'SMTP_ACCEPTED';
UPDATE TEAM_INVITATION SET STATUS = 'FAILED', TOKEN_HASH = NULL WHERE STATUS = 'SENDING';
UPDATE TEAM_INVITATION SET REPLACEMENT_TOKEN_HASH = NULL, REPLACEMENT_EXPIRES_AT = NULL;

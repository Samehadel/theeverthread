CREATE TABLE EMAIL_OUTBOX (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    MESSAGE_KEY UUID NOT NULL UNIQUE,
    VERIFICATION_ID BIGINT REFERENCES VERIFICATION_EMAIL(ACCOUNT_ID) ON DELETE CASCADE,
    INVITATION_ID BIGINT REFERENCES TEAM_INVITATION(ID) ON DELETE CASCADE,
    TOKEN_HASH VARCHAR(64) NOT NULL,
    PAYLOAD BYTEA,
    EXPIRES_AT TIMESTAMPTZ NOT NULL,
    STATE TEXT NOT NULL DEFAULT 'QUEUED',
    PROVIDER_ID TEXT UNIQUE,
    OUTCOME TEXT,
    REASON TEXT,
    EVENT_AT TIMESTAMPTZ,
    ATTEMPTS INTEGER NOT NULL DEFAULT 0,
    FIRST_ATTEMPT TIMESTAMPTZ,
    NEXT_ATTEMPT TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CLAIM UUID,
    NEXT_CHECK TIMESTAMPTZ,
    CHECK (num_nonnulls(VERIFICATION_ID, INVITATION_ID) = 1)
);
CREATE INDEX EMAIL_TO_SEND ON EMAIL_OUTBOX(NEXT_ATTEMPT) WHERE STATE IN ('QUEUED','SENDING');
CREATE INDEX EMAIL_TO_CHECK ON EMAIL_OUTBOX(NEXT_CHECK) WHERE NEXT_CHECK IS NOT NULL;
CREATE INDEX EMAIL_VERIFICATION_HISTORY ON EMAIL_OUTBOX(VERIFICATION_ID, ID DESC);
CREATE INDEX EMAIL_INVITATION_HISTORY ON EMAIL_OUTBOX(INVITATION_ID, ID DESC);
CREATE TABLE EMAIL_EVENT (
    EVENT_KEY TEXT PRIMARY KEY,
    PROVIDER_ID TEXT NOT NULL,
    MESSAGE_KEY UUID,
    OUTCOME TEXT NOT NULL,
    OCCURRED_AT TIMESTAMPTZ NOT NULL,
    REASON TEXT
);
CREATE INDEX EMAIL_PROVIDER_EVENTS ON EMAIL_EVENT(PROVIDER_ID, OCCURRED_AT);

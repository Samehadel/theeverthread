CREATE FUNCTION PRESERVE_WORKSPACE_TICKET() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.WORKSPACE_ID <> OLD.WORKSPACE_ID OR NEW.AUTHOR_ID <> OLD.AUTHOR_ID THEN
        RAISE EXCEPTION 'Ticket workspace and creator are immutable' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;
--changeset betterf:20261021-006-ticket-ownership-trigger
CREATE TRIGGER WORKSPACE_TICKET_IMMUTABLE BEFORE UPDATE ON KNOWLEDGE_TICKET
    FOR EACH ROW EXECUTE FUNCTION PRESERVE_WORKSPACE_TICKET();
